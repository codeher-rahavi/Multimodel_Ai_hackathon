import { useState, useRef, useEffect } from 'react';
import {
  Send,
  Sparkles,
  Paperclip,
  BookOpen,
  Quote,
  AlertCircle,
  User,
  CornerDownLeft,
  RefreshCw,
} from 'lucide-react';
import { Card } from '@/components/ui/Card';
import { Badge } from '@/components/ui/Badge';
import { askTutor, type TutorMessage } from '@/lib/tutorApi';
import type { ChatMessage } from '@/types';

const suggestedQuestions = [
  'Explain the difference between BFS and DFS',
  'What are the ACID properties in databases?',
  'How does TCP three-way handshake work?',
  'What is a binary search tree?',
];

const welcomeMessage: ChatMessage = {
  id: 'welcome',
  role: 'tutor',
  content:
    "Hi! I'm your AI Study Companion, powered by Google Gemini. Ask me anything about your courses — concepts, algorithms, formulas, or study strategies.\n\nNote: Document-based answers and source citations are not yet implemented. I'll answer from my general knowledge for now.",
  timestamp: '',
};

export function AITutor() {
  const [messages, setMessages] = useState<ChatMessage[]>([welcomeMessage]);
  const [input, setInput] = useState('');
  const [isTyping, setIsTyping] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const messagesEndRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    messagesEndRef.current?.scrollIntoView({ behavior: 'smooth' });
  }, [messages, isTyping]);

  const handleSend = async (text?: string) => {
    const content = text ?? input.trim();
    if (!content || isTyping) return;

    setError(null);

    const userMsg: ChatMessage = {
      id: `c-${Date.now()}`,
      role: 'user',
      content,
      timestamp: new Date().toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit' }),
    };
    setMessages((prev) => [...prev, userMsg]);
    setInput('');
    setIsTyping(true);

    try {
      // Build conversation history for context (exclude welcome message)
      const history: TutorMessage[] = messages
        .filter((m) => m.id !== 'welcome')
        .map((m) => ({
          role: m.role,
          content: m.content,
        }));

      const result = await askTutor(content, history);

      const tutorMsg: ChatMessage = {
        id: `c-${Date.now()}-r`,
        role: 'tutor',
        content: result.answer,
        timestamp: new Date().toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit' }),
      };
      setMessages((prev) => [...prev, tutorMsg]);
    } catch (err) {
      const message = err instanceof Error ? err.message : 'Something went wrong. Please try again.';
      setError(message);
    } finally {
      setIsTyping(false);
    }
  };

  const handleClearChat = () => {
    setMessages([welcomeMessage]);
    setError(null);
  };

  return (
    <div className="space-y-4 animate-fade-in h-full flex flex-col">
      {/* Info notice */}
      <div className="flex items-start gap-3 p-3.5 rounded-xl bg-brand-50 border border-brand-200/50 flex-shrink-0">
        <Sparkles className="w-4 h-4 text-brand-600 flex-shrink-0 mt-0.5" />
        <div className="flex-1">
          <p className="text-xs text-brand-800">
            <span className="font-medium">AI Tutor is live!</span> Answers are generated by Google Gemini.
          </p>
          <p className="text-xs text-brand-600 mt-0.5">
            Document-based answers and source citations are not yet implemented.
          </p>
        </div>
        <button
          onClick={handleClearChat}
          className="text-xs text-brand-600 hover:text-brand-800 font-medium flex items-center gap-1 flex-shrink-0"
        >
          <RefreshCw className="w-3 h-3" /> Clear
        </button>
      </div>

      {/* Error banner */}
      {error && (
        <div className="flex items-start gap-3 p-3.5 rounded-xl bg-rose-50 border border-rose-200/50 flex-shrink-0 animate-slide-up">
          <AlertCircle className="w-4 h-4 text-rose-600 flex-shrink-0 mt-0.5" />
          <div className="flex-1">
            <p className="text-xs font-medium text-rose-800">Couldn't get a response</p>
            <p className="text-xs text-rose-600 mt-0.5">{error}</p>
          </div>
          <button
            onClick={() => setError(null)}
            className="text-xs text-rose-500 hover:text-rose-700 font-medium flex-shrink-0"
          >
            Dismiss
          </button>
        </div>
      )}

      {/* Chat area */}
      <Card className="flex-1 flex flex-col overflow-hidden min-h-0">
        {/* Chat header */}
        <div className="flex items-center justify-between px-5 py-3.5 border-b border-slate-100 flex-shrink-0">
          <div className="flex items-center gap-3">
            <div className="w-10 h-10 rounded-xl bg-gradient-to-br from-brand-500 to-brand-700 flex items-center justify-center">
              <Sparkles className="w-5 h-5 text-white" />
            </div>
            <div>
              <h3 className="text-sm font-semibold text-slate-900">AI Tutor</h3>
              <p className="text-xs text-slate-400">Powered by Google Gemini</p>
            </div>
          </div>
          <Badge color="green" size="sm" dot>Online</Badge>
        </div>

        {/* Messages */}
        <div className="flex-1 overflow-y-auto scrollbar-thin p-5 space-y-5 min-h-0">
          {messages.map((msg) => (
            <MessageBubble key={msg.id} message={msg} />
          ))}

          {isTyping && (
            <div className="flex items-start gap-3 animate-fade-in">
              <div className="w-8 h-8 rounded-lg bg-gradient-to-br from-brand-500 to-brand-700 flex items-center justify-center flex-shrink-0">
                <Sparkles className="w-4 h-4 text-white" />
              </div>
              <div className="bg-slate-100 rounded-2xl rounded-tl-md px-4 py-3 flex items-center gap-1.5">
                <span className="w-2 h-2 bg-slate-400 rounded-full animate-bounce" style={{ animationDelay: '0ms' }} />
                <span className="w-2 h-2 bg-slate-400 rounded-full animate-bounce" style={{ animationDelay: '150ms' }} />
                <span className="w-2 h-2 bg-slate-400 rounded-full animate-bounce" style={{ animationDelay: '300ms' }} />
              </div>
            </div>
          )}

          <div ref={messagesEndRef} />
        </div>

        {/* Suggested questions */}
        {messages.length <= 1 && !isTyping && (
          <div className="px-5 pb-3 flex-shrink-0">
            <p className="text-xs text-slate-400 font-medium mb-2">Try asking:</p>
            <div className="flex flex-wrap gap-2">
              {suggestedQuestions.map((q) => (
                <button
                  key={q}
                  onClick={() => handleSend(q)}
                  disabled={isTyping}
                  className="text-xs text-slate-600 bg-slate-100 hover:bg-brand-50 hover:text-brand-700 disabled:opacity-50 px-3 py-1.5 rounded-full transition-colors"
                >
                  {q}
                </button>
              ))}
            </div>
          </div>
        )}

        {/* Input */}
        <div className="border-t border-slate-100 p-4 flex-shrink-0">
          <div className="flex items-end gap-2 bg-slate-50 rounded-2xl border border-slate-200 p-2 focus-within:border-brand-400 focus-within:bg-white transition-colors">
            <button className="p-2 text-slate-400 hover:text-slate-600 rounded-lg hover:bg-slate-100 transition-colors" title="Document attachments not yet implemented">
              <Paperclip className="w-5 h-5" />
            </button>
            <textarea
              value={input}
              onChange={(e) => setInput(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === 'Enter' && !e.shiftKey) {
                  e.preventDefault();
                  handleSend();
                }
              }}
              placeholder="Ask a question about your studies..."
              rows={1}
              className="flex-1 bg-transparent text-sm text-slate-700 placeholder-slate-400 outline-none resize-none py-2 max-h-32"
            />
            <button
              onClick={() => handleSend()}
              disabled={!input.trim() || isTyping}
              className="w-9 h-9 rounded-xl bg-brand-600 text-white flex items-center justify-center hover:bg-brand-700 disabled:opacity-40 disabled:cursor-not-allowed transition-colors flex-shrink-0"
            >
              <Send className="w-4 h-4" />
            </button>
          </div>
          <p className="text-[10px] text-slate-400 mt-2 flex items-center gap-1 justify-center">
            <CornerDownLeft className="w-3 h-3" /> Press Enter to send · Shift + Enter for new line
          </p>
        </div>
      </Card>
    </div>
  );
}

function MessageBubble({ message }: { message: ChatMessage }) {
  const isUser = message.role === 'user';

  return (
    <div className={`flex items-start gap-3 animate-slide-up ${isUser ? 'flex-row-reverse' : ''}`}>
      {/* Avatar */}
      <div className={`w-8 h-8 rounded-lg flex items-center justify-center flex-shrink-0 ${
        isUser ? 'bg-slate-200' : 'bg-gradient-to-br from-brand-500 to-brand-700'
      }`}>
        {isUser ? <User className="w-4 h-4 text-slate-500" /> : <Sparkles className="w-4 h-4 text-white" />}
      </div>

      {/* Message content */}
      <div className={`max-w-[80%] ${isUser ? 'items-end' : 'items-start'} flex flex-col gap-2`}>
        <div className={`rounded-2xl px-4 py-3 ${
          isUser
            ? 'bg-brand-600 text-white rounded-tr-md'
            : 'bg-slate-100 text-slate-700 rounded-tl-md'
        }`}>
          <p className="text-sm leading-relaxed whitespace-pre-wrap">{message.content}</p>
        </div>

        {/* Citations — not yet implemented, shown only when citations exist */}
        {message.citations && message.citations.length > 0 && (
          <div className="space-y-2 w-full">
            <p className="text-[10px] font-semibold text-slate-400 uppercase tracking-wider flex items-center gap-1">
              <BookOpen className="w-3 h-3" /> Source Citations
            </p>
            {message.citations.map((citation) => (
              <div key={citation.id} className="flex items-start gap-2.5 p-3 rounded-xl bg-white border border-slate-200 hover:border-brand-300 transition-colors">
                <Quote className="w-4 h-4 text-brand-500 flex-shrink-0 mt-0.5" />
                <div className="flex-1 min-w-0">
                  <div className="flex items-center gap-2 mb-1">
                    <span className="text-xs font-semibold text-slate-700">{citation.source}</span>
                    <Badge color="brand" size="sm">{citation.page}</Badge>
                  </div>
                  <p className="text-xs text-slate-500 leading-relaxed italic">"{citation.snippet}"</p>
                </div>
              </div>
            ))}
          </div>
        )}

        {message.timestamp && (
          <span className="text-[10px] text-slate-400 px-1">{message.timestamp}</span>
        )}
      </div>
    </div>
  );
}
